"""
Chroma-backed retrieval for the agent's explain node. Runs embedded
(`chromadb.PersistentClient`) rather than against the separate networked `chroma` service
in docker-compose.yml — simpler, no server to coordinate, and easier to test (point at a
temp directory). See docs/specs/M6-rag-knowledge-base.md for why.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

COLLECTION_NAME = "veterinary_reference"

DEFAULT_PERSIST_DIR = Path(__file__).resolve().parents[2] / "data" / "chroma_db"

_collection_cache: dict[str, Any] = {}


def _get_collection(persist_dir: Path | None = None):
    # Imported lazily so importing this module doesn't require chromadb to be installed
    # unless retrieval is actually used — keeps ml-service importable in contexts that
    # don't touch RAG.
    import chromadb
    from chromadb.utils import embedding_functions

    path = str(persist_dir or DEFAULT_PERSIST_DIR)
    if path not in _collection_cache:
        client = chromadb.PersistentClient(path=path)
        _collection_cache[path] = client.get_or_create_collection(
            COLLECTION_NAME, embedding_function=embedding_functions.DefaultEmbeddingFunction()
        )
    return _collection_cache[path]


def retrieve(query: str, k: int = 3, persist_dir: Path | None = None) -> list[dict[str, str]]:
    """Returns up to k relevant chunks for `query`, each `{"text": ..., "source": ...}`.
    Returns [] (never raises) if the collection is empty or unreachable — retrieval failure
    must degrade gracefully, same principle as the explain node's LLM failure handling.

    Restricted to "overview" chunks (M10) — precautions/next-steps content lives in the same
    collection now, but must never get pulled into the LLM-grounded `explanation` prompt;
    see get_precautions() for how that content is actually looked up."""
    try:
        collection = _get_collection(persist_dir)
        count = collection.count()
        if count == 0:
            return []

        results = collection.query(
            query_texts=[query], n_results=min(k, count), where={"section": "overview"}
        )
        documents = results.get("documents") or [[]]
        metadatas = results.get("metadatas") or [[]]

        return [
            {"text": doc, "source": meta.get("source", "unknown")}
            for doc, meta in zip(documents[0], metadatas[0])
        ]
    except Exception:
        return []


# M10: precautions/next-steps are looked up verbatim by exact (source, section) match, never
# generated by the LLM — see docs/specs/M10-precautions-next-steps.md's design decision.
# Every entry in app/agent/graph.py's REPORTABLE_DISEASES must have a slug here — a
# reportable diagnosis with no guidance doc reads as "no action needed," which
# tests/test_rag_retrieval.py guards against (see docs/DISCLAIMER.md).
DIAGNOSIS_TO_DOC_SLUG = {
    "Foot and Mouth Disease": "foot-and-mouth-disease",
    "Lumpy Skin Disease": "lumpy-skin-disease",
    "Mastitis": "mastitis",
    "Bovine Respiratory Disease": "bovine-respiratory-disease",
    "Healthy": "healthy",
    "PPR (Peste des Petits Ruminants)": "peste-des-petits-ruminants",
}

# "uncertain" isn't a disease, so it has no reference doc — mirrors
# app/agent/graph.py's _template_explanation's hardcoded uncertain-case wording.
_UNCERTAIN_PRECAUTIONS = [
    "Keep monitoring the animal closely for any new or worsening symptoms.",
]
_UNCERTAIN_NEXT_STEPS = [
    "Provide more symptom details for a more confident prediction, or consult a vet directly.",
]


def _bullets(text: str) -> list[str]:
    return [line.strip().lstrip("-•").strip() for line in text.splitlines() if line.strip()]


def get_precautions(diagnosis: str, persist_dir: Path | None = None) -> dict[str, list[str]]:
    """Returns {"precautions": [...], "next_steps": [...]} for a diagnosis — an exact
    metadata lookup, not a similarity search, so it can never surface the wrong disease's
    guidance. Returns empty lists (never raises) on any failure, same "never blocks a
    diagnosis" principle as retrieve()."""
    if diagnosis == "uncertain":
        return {"precautions": list(_UNCERTAIN_PRECAUTIONS), "next_steps": list(_UNCERTAIN_NEXT_STEPS)}

    slug = DIAGNOSIS_TO_DOC_SLUG.get(diagnosis)
    if slug is None:
        return {"precautions": [], "next_steps": []}

    try:
        collection = _get_collection(persist_dir)
        result = collection.get(where={"source": slug})
        documents = result.get("documents") or []
        metadatas = result.get("metadatas") or []
        by_section = {meta.get("section"): doc for doc, meta in zip(documents, metadatas)}
    except Exception:
        return {"precautions": [], "next_steps": []}

    return {
        "precautions": _bullets(by_section.get("precautions", "")),
        "next_steps": _bullets(by_section.get("next-steps", "")),
    }
